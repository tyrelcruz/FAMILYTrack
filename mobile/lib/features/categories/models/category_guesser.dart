  /// The best match among [options], or null if nothing matches.
  static String? guess(String text, List<Category> options) {
    final input =
        ' ${text.toLowerCase().replaceAll(RegExp(r'[^a-z0-9\- ]'), ' ')} ';
    if (input.trim().isEmpty) return null;
    String? best;
    var bestScore = 0;
    for (final c in options) {
      var score = 0;
      for (final k in _keywords[c.id] ?? const <String>[]) {
        // Whole words only, so "gas" doesn't match "gastos".
        if (input.contains(' $k ')) score += k.contains(' ') ? 2 : 1;
      }
      if (score > bestScore) {
        bestScore = score;
        best = c.id;
      }
    }
    return best;
  }
